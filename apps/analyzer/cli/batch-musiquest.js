#!/usr/bin/env node
/**
 * batch-musiquest.js — run every config in apps/analyzer/configs/musiquest/
 * through generate-samples.js, stage the resulting .hki + def JSONs into
 * handoff/musiquest/, and write one aggregated generation-report.md.
 *
 * Usage:
 *   node apps/analyzer/cli/batch-musiquest.js            # all configs
 *   node apps/analyzer/cli/batch-musiquest.js violin oboe # subset by key
 *
 * Each config runs in its own child process with the same heap/GC flags as
 * `npm run analyze` (--max-old-space-size=8192 --expose-gc): the per-note
 * PCM buffers only release on GC, and a crash/OOM in one instrument must
 * not kill the batch. Aggregation reads out/<key>-summary.json (emitted by
 * generate-samples.js), never report.md.
 *
 * Exits non-zero if any config crashed or produced no summary, but only
 * after every config has been attempted.
 */

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '..', '..', '..');
const CFG_DIR = path.join(REPO, 'apps', 'analyzer', 'configs', 'musiquest');
const OUT_DIR = path.join(REPO, 'apps', 'analyzer', 'out');
const GEN = path.join(__dirname, 'generate-samples.js');
const HANDOFF = path.join(REPO, 'handoff', 'musiquest');
const HANDOFF_DEFS = path.join(HANDOFF, 'defs');

const only = process.argv.slice(2); // optional instrumentKey filter

const cfgPaths = fs.readdirSync(CFG_DIR)
  .filter(f => f.endsWith('.json'))
  .sort()
  .map(f => path.join(CFG_DIR, f));

/* With key filters, only the named instruments re-run — but staging and the
   aggregate report still cover EVERY config, using each skipped key's existing
   out/<key>-summary.json. A subset re-run therefore refreshes its rows in
   place instead of clobbering the report down to the subset. */
const runs = [];
for (const cfgPath of cfgPaths) {
  const cfg = JSON.parse(fs.readFileSync(cfgPath, 'utf8'));
  const key = cfg.instrumentKey;
  const rerun = only.length === 0 || only.includes(key);
  const run = { key, cfgPath, decays: !!cfg.decays, crashed: false };
  if (rerun) {
    console.error(`\n=== ${key} (${path.basename(cfgPath)}) ===`);
    const res = spawnSync('node',
      ['--max-old-space-size=8192', '--expose-gc', GEN, cfgPath],
      { stdio: ['ignore', 'ignore', 'inherit'] });
    run.crashed = res.status !== 0;
  }
  const summaryPath = path.join(OUT_DIR, `${key}-summary.json`);
  try {
    run.summary = JSON.parse(fs.readFileSync(summaryPath, 'utf8'));
  } catch {
    run.summary = null;
    if (rerun) run.crashed = true;
  }
  runs.push(run);
}

/* Stage artifacts. Copy (not move) so out/ stays a regenerable cache.
   bundleBytes is set by generate-samples only when THIS run wrote a bundle —
   a null means no fresh .hki exists, and any same-keyed file sitting in out/
   is a stale leftover from an earlier config generation. Staging it would
   silently ship the wrong instrument (bit us when the MQ configs switched to
   CDN sources without "bundle": true). */
fs.mkdirSync(HANDOFF_DEFS, { recursive: true });
let staged = 0;
for (const run of runs) {
  if (run.crashed || !run.summary || run.summary.picked === 0) continue;
  if (run.summary.bundleBytes == null) {
    console.error(`WARN ${run.key}: no bundle produced this run (CDN config without "bundle": true?) — not staged`);
    run.crashed = true;
    continue;
  }
  const hkiSrc = path.join(OUT_DIR, `${run.key}.hki`);
  const defSrc = path.join(OUT_DIR, `${run.key}-def.json`);
  if (!fs.existsSync(hkiSrc) || !fs.existsSync(defSrc)) { run.crashed = true; continue; }
  fs.copyFileSync(hkiSrc, path.join(HANDOFF, `${run.key}.hki`));
  fs.copyFileSync(defSrc, path.join(HANDOFF_DEFS, `${run.key}.json`));
  staged++;
}

/* Aggregate report. */
const fmtMB = n => `${(n / (1024 * 1024)).toFixed(2)} MB`;
const lines = [];
lines.push('# MusiQuest instrument generation report');
lines.push('');
lines.push(`Generated by \`apps/analyzer/cli/batch-musiquest.js\` — ${runs.length} configs, ${staged} staged.`);
lines.push('');
lines.push('| Instrument | Path | Analyzed | Picked | G / B / Y / R / F | Bundle |');
lines.push('| --- | --- | ---: | ---: | :---: | ---: |');
let totalBytes = 0;
for (const run of runs) {
  const s = run.summary;
  if (!s) { lines.push(`| ${run.key} | — | — | — | CRASHED | — |`); continue; }
  const t = s.tiers;
  totalBytes += s.bundleBytes || 0;
  const flag = run.crashed ? ' ⚠️' : '';
  lines.push(`| ${s.instrumentKey}${flag} | ${s.path}${s.vibrato ? ' (vib)' : ''} | ${s.analyzed} | ${s.picked} | ${t.green} / ${t.blue} / ${t.yellow} / ${t.red} / ${t.fail} | ${s.bundleBytes ? fmtMB(s.bundleBytes) : '—'} |`);
}
lines.push('');
lines.push(`**Total staged bundle size: ${fmtMB(totalBytes)}**`);
lines.push('');

/* Poor-loop / hand-investigation queue. Loop instruments where reds+fails
   dominate or the picked spine is sparse relative to the range. */
const flagged = runs.filter(r => {
  const s = r.summary;
  if (!s || r.crashed) return true;
  if (s.path !== 'loop') return false;
  const poor = (s.tiers.red + s.tiers.fail) / Math.max(1, s.analyzed);
  const expectedPicks = Math.floor(s.analyzed / (s.pickSpacing || 4)) + 1;
  return poor > 0.5 || s.picked < expectedPicks * 0.6;
});
lines.push('## Hand-investigation queue');
lines.push('');
if (flagged.length === 0) {
  lines.push('None — every loop instrument produced a healthy pick spine.');
} else {
  for (const run of flagged) {
    const s = run.summary;
    if (!s) { lines.push(`### ${run.key} — CRASHED (no summary)`); lines.push(''); continue; }
    lines.push(`### ${s.instrumentKey} — ${s.picked} picks from ${s.analyzed} analyzed (${s.tiers.red} red, ${s.tiers.fail} fail)`);
    lines.push('');
    const reasons = {};
    for (const f of s.fails) {
      const r = f.reason || '(red: <3 segments or SCC broken)';
      reasons[r] = (reasons[r] || 0) + 1;
    }
    for (const [reason, count] of Object.entries(reasons).sort((a, b) => b[1] - a[1])) {
      lines.push(`- ${count}× ${reason}`);
    }
    lines.push('');
  }
}

const reportPath = path.join(HANDOFF, 'generation-report.md');
fs.writeFileSync(reportPath, lines.join('\n') + '\n');
console.error(`\nwrote: ${reportPath}`);
console.error(`staged: ${staged}/${runs.length} instruments, total ${fmtMB(totalBytes)}`);

const crashed = runs.filter(r => r.crashed);
if (crashed.length > 0) {
  console.error(`FAILED configs: ${crashed.map(r => r.key).join(', ')}`);
  process.exit(1);
}
